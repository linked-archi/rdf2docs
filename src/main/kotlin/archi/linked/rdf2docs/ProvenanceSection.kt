package archi.linked.rdf2docs

import org.eclipse.rdf4j.model.IRI
import org.eclipse.rdf4j.model.Literal
import org.eclipse.rdf4j.model.vocabulary.RDF
import org.eclipse.rdf4j.repository.RepositoryConnection
import java.util.concurrent.ConcurrentHashMap

/**
 * Where a resource came from, read from the PROV statements a converter writes, for the *Provenance* tab of
 * its page.
 *
 * A converter records provenance at up to three levels: on the resource itself (a Backstage entity's
 * `prov:wasDerivedFrom` and qualified derivation; the file a BPMN or PlantUML view was drawn in), on the named
 * graph that holds it (`{ns}graph/semantic`, a `prov:Bundle`), and on its model. The tab shows the most
 * specific level that records anything, and says which level that was. Without named graphs — a Turtle input
 * — the graph level is empty and the model's record is shown.
 *
 * The provenance resources — the conversion run, the converter, the source file, the graphs — have pages of
 * their own, and [referencesHtml] gives each of them the other direction: what the run generated, what was
 * derived from the file.
 */
internal object ProvenanceSection {

    const val PROV = "http://www.w3.org/ns/prov#"

    private const val SCHEMA = "https://schema.org/"

    /** What one resource, graph or model records about its origin. */
    private data class Record(
        val holder: String,
        val level: Level,
        val sources: List<String>,
        val activities: List<String>,
        val generatedAt: List<String>,
    ) {
        val isEmpty: Boolean get() = sources.isEmpty() && activities.isEmpty() && generatedAt.isEmpty()
    }

    private enum class Level { RESOURCE, GRAPH, MODEL }

    /** A run and the converters that ran it, as found once per run of the generator. */
    private data class Activity(val agents: List<String>, val started: String?)

    // Every element of a model shares its graph's record, so each is read once per generation run rather than
    // once per page. Read from every generation coroutine, hence concurrent maps; [reset] empties them.
    private val records = ConcurrentHashMap<Pair<String, Level>, Record>()
    private val activities = ConcurrentHashMap<String, Activity>()
    private val labels = ConcurrentHashMap<String, String>()

    /** Forgets what an earlier generation run read. */
    fun reset() {
        records.clear()
        activities.clear()
        labels.clear()
    }

    /** The *Provenance* tab of the page of [iri], or an empty string when nothing records where it came from. */
    fun html(conn: RepositoryConnection, site: Site, iri: String, back: String, ns: Namespaces): String {
        val records = recordsFor(conn, iri, ns)
        if (records.isEmpty()) return ""
        val rows = records.joinToString("\n") { r ->
            val recordedOn = when (r.level) {
                Level.RESOURCE -> "this resource"
                Level.GRAPH -> "its graph ${link(conn, site, r.holder, back)}"
                Level.MODEL -> "its model ${link(conn, site, r.holder, back)}"
            }
            val sources = r.sources.joinToString("<br>") { link(conn, site, it, back) }
            val activities = r.activities.joinToString("<br>") { activityHtml(conn, site, it, back) }
            val generated = r.generatedAt.joinToString("<br>") { escapeHtml(it) }
            "            <tr><td>$recordedOn</td><td>$sources</td><td>$activities</td><td>$generated</td></tr>"
        }
        return """
    <table><thead><tr><th>Recorded on</th><th>Derived from</th><th>Generated by</th><th>Generated at</th></tr></thead>
    <tbody>
$rows
    </tbody></table>"""
    }

    /**
     * The *Referenced by* tab of a provenance resource's page: every statement in the PROV vocabulary whose
     * object it is, so a run lists what it generated and a source file what was derived from it.
     */
    fun referencesHtml(conn: RepositoryConnection, site: Site, iri: String, back: String): String {
        val query = """
            SELECT DISTINCT ?subject ?predicate WHERE {
                ?subject ?predicate <$iri> .
                FILTER(STRSTARTS(STR(?predicate), "$PROV"))
            } ORDER BY ?predicate ?subject
        """.trimIndent()
        val rows = mutableListOf<String>()
        conn.prepareTupleQuery(query).evaluate().use { res ->
            while (res.hasNext()) {
                val b = res.next()
                val subject = b.getValue("subject")?.stringValue() ?: continue
                val predicate = b.getValue("predicate") as? IRI ?: continue
                val subjectCell = if (b.getValue("subject") is IRI) link(conn, site, subject, back) else escapeHtml(subject)
                rows.add(
                    "            <tr><td>$subjectCell</td><td><a href=\"${escapeHtml(predicate.stringValue())}\" " +
                        "target=\"_blank\">${escapeHtml(predicate.localName)}</a></td></tr>"
                )
            }
        }
        if (rows.isEmpty()) return ""
        return """
    <table><thead><tr><th>Resource</th><th>Relation</th></tr></thead>
    <tbody>
${rows.joinToString("\n")}
    </tbody></table>"""
    }

    private fun recordsFor(conn: RepositoryConnection, iri: String, ns: Namespaces): List<Record> {
        val own = record(conn, iri, Level.RESOURCE)
        if (!own.isEmpty) return listOf(own)

        val vf = conn.valueFactory
        val subject = vf.createIRI(iri)
        // The graphs that say what the resource is. The other graphs that mention it — a folder placement, a
        // view's membership — are about where it is shown rather than where it came from.
        val graphs = conn.getStatements(subject, RDF.TYPE, null, true).use { res ->
            res.mapNotNull { it.context?.stringValue() }
        }.distinct().sorted()
        val fromGraphs = graphs.map { record(conn, it, Level.GRAPH) }.filterNot { it.isEmpty }
        if (fromGraphs.isNotEmpty()) return fromGraphs

        val models = conn.getStatements(subject, vf.createIRI(ns.core, "inModel"), null, true).use { res ->
            res.mapNotNull { (it.`object` as? IRI)?.stringValue() }
        }.distinct().sorted()
        return models.map { record(conn, it, Level.MODEL) }.filterNot { it.isEmpty }
    }

    private fun record(conn: RepositoryConnection, holder: String, level: Level): Record =
        records.getOrPut(holder to level) { readRecord(conn, holder, level) }

    private fun readRecord(conn: RepositoryConnection, holder: String, level: Level): Record {
        val query = """
            PREFIX prov: <$PROV>
            SELECT ?source ?activity ?at WHERE {
                { <$holder> prov:wasDerivedFrom ?source }
                UNION { <$holder> prov:qualifiedDerivation ?derivation .
                        ?derivation prov:entity ?source .
                        OPTIONAL { ?derivation prov:hadActivity ?activity } }
                UNION { <$holder> prov:wasGeneratedBy ?activity }
                UNION { <$holder> prov:generatedAtTime ?at }
            }
        """.trimIndent()
        val sources = sortedSetOf<String>()
        val activities = sortedSetOf<String>()
        val generatedAt = sortedSetOf<String>()
        conn.prepareTupleQuery(query).evaluate().use { res ->
            while (res.hasNext()) {
                val b = res.next()
                (b.getValue("source") as? IRI)?.let { sources.add(it.stringValue()) }
                (b.getValue("activity") as? IRI)?.let { activities.add(it.stringValue()) }
                (b.getValue("at") as? Literal)?.let { generatedAt.add(it.stringValue()) }
            }
        }
        return Record(holder, level, sources.toList(), activities.toList(), generatedAt.toList())
    }

    /** A run as "the run, by the converter that ran it, started then", each part a link where it has a page. */
    private fun activityHtml(conn: RepositoryConnection, site: Site, activity: String, back: String): String {
        val found = activities.getOrPut(activity) { readActivity(conn, activity) }
        val sb = StringBuilder(link(conn, site, activity, back))
        if (found.agents.isNotEmpty()) sb.append(" by ").append(found.agents.joinToString(", ") { link(conn, site, it, back) })
        found.started?.let { sb.append(", started ").append(escapeHtml(it)) }
        return sb.toString()
    }

    private fun readActivity(conn: RepositoryConnection, activity: String): Activity {
        val query = """
            PREFIX prov: <$PROV>
            SELECT ?agent ?started WHERE {
                OPTIONAL { <$activity> prov:wasAssociatedWith ?agent }
                OPTIONAL { <$activity> prov:startedAtTime ?started }
            }
        """.trimIndent()
        val agents = sortedSetOf<String>()
        var started: String? = null
        conn.prepareTupleQuery(query).evaluate().use { res ->
            while (res.hasNext()) {
                val b = res.next()
                (b.getValue("agent") as? IRI)?.let { agents.add(it.stringValue()) }
                if (started == null) started = (b.getValue("started") as? Literal)?.stringValue()
            }
        }
        return Activity(agents.toList(), started)
    }

    private fun link(conn: RepositoryConnection, site: Site, iri: String, back: String): String {
        val text = escapeHtml(labels.getOrPut(iri) { label(conn, iri, site.baseIri) })
        val href = site.href(iri, back) ?: return text
        val target = if (iri.startsWith(site.baseIri)) "" else " target=\"_blank\""
        return "<a href=\"${escapeHtml(href)}\"$target>$text</a>"
    }

    /**
     * What a provenance resource is called: its label or name, with the software version for a converter, and
     * otherwise its IRI below the base (`provenance/run/6487efcc`, `model/payment-platform/graph/semantic`),
     * which says more than a last segment of eight hex digits.
     */
    private fun label(conn: RepositoryConnection, iri: String, baseIri: String): String {
        val query = """
            PREFIX skos: <http://www.w3.org/2004/02/skos/core#>
            PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
            PREFIX schema: <$SCHEMA>
            SELECT ?label ?name ?rdfsLabel ?version WHERE {
                OPTIONAL { <$iri> skos:prefLabel ?label }
                OPTIONAL { <$iri> schema:name ?name }
                OPTIONAL { <$iri> rdfs:label ?rdfsLabel }
                OPTIONAL { <$iri> schema:softwareVersion ?version }
            } LIMIT 1
        """.trimIndent()
        conn.prepareTupleQuery(query).evaluate().use { res ->
            if (res.hasNext()) {
                val b = res.next()
                val name = listOf("label", "name", "rdfsLabel").firstNotNullOfOrNull { (b.getValue(it) as? Literal)?.stringValue() }
                val version = (b.getValue("version") as? Literal)?.stringValue()
                if (name != null) return if (version != null) "$name $version" else name
            }
        }
        return if (iri.startsWith(baseIri)) PagePaths.relative(iri, baseIri) else iri
    }

    private fun escapeHtml(text: String) = text
        .replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        .replace("\"", "&quot;").replace("'", "&#39;")
}
